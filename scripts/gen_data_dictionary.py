"""Generate docs/data_dictionary.md from the dbt model YAML and the raw Arrow schemas.

    uv run python scripts/gen_data_dictionary.py

The mart sections are produced from the contract YAML (column, type, description, tests), so the
dictionary cannot drift from what dbt enforces. CI does not regenerate it; re-run after
changing a model's YAML.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from musicpods.glue import schemas

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "dbt" / "models"
OUT = ROOT / "docs" / "data_dictionary.md"

RAW = {
    "listen_events": (
        schemas.LISTEN_EVENTS,
        "Firehose sink: one row per listen, deduplicated on event_id; partitioned by day(listened_at).",
    ),
    "mb_artists": (schemas.MB_ARTISTS, "MusicBrainz artists, latest fetch per MBID."),
    "mb_artist_tags": (
        schemas.MB_ARTIST_TAGS,
        "MusicBrainz artist tags (CC BY-NC-SA 3.0) with an is_genre flag from the official genre list.",
    ),
    "mb_recordings": (schemas.MB_RECORDINGS, "MusicBrainz recordings, latest fetch per MBID."),
    "mb_release_groups": (
        schemas.MB_RELEASE_GROUPS,
        "MusicBrainz release groups, latest fetch per MBID.",
    ),
    "lb_fresh_releases": (
        schemas.LB_FRESH_RELEASES,
        "ListenBrainz fresh releases, one row per daily snapshot and release.",
    ),
    "lb_sitewide_artists": (
        schemas.LB_SITEWIDE_ARTISTS,
        "ListenBrainz sitewide top artists per snapshot.",
    ),
    "lb_user_daily_activity": (
        schemas.LB_USER_DAILY_ACTIVITY,
        "Published per-user daily listen counts (reconciliation source).",
    ),
    "lb_user_top_artists": (
        schemas.LB_USER_TOP_ARTISTS,
        "Published per-user weekly top artists (reconciliation source).",
    ),
    "podcast_chart_entries": (
        schemas.PODCAST_CHART_ENTRIES,
        "Apple Podcasts Top Shows, one row per snapshot, storefront and rank; partitioned by snapshot_date.",
    ),
    "podcast_shows": (
        schemas.PODCAST_SHOWS,
        "iTunes Lookup metadata per lookup date and storefront.",
    ),
    "podcast_episodes": (
        schemas.PODCAST_EPISODES,
        "Episodes parsed from each show's RSS feed (metadata only); partitioned by fetched_date.",
    ),
    "lastfm_top_artists": (schemas.LASTFM_TOP_ARTISTS, "Optional (LASTFM_API_KEY)."),
    "podcastindex_feeds": (schemas.PODCASTINDEX_FEEDS, "Optional (PODCASTINDEX_API_KEY/SECRET)."),
    "spotify_artists": (
        schemas.SPOTIFY_ARTISTS,
        "Optional (SPOTIFY_CLIENT_ID/SECRET); catalogue metadata only.",
    ),
}


def _tests(col: dict) -> str:
    names = []
    for t in col.get("data_tests", []) or []:
        names.append(t if isinstance(t, str) else next(iter(t)))
    return ", ".join(names)


def _esc(text: str) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def main() -> None:
    lines = [
        "# Data dictionary",
        "",
        "Generated by `scripts/gen_data_dictionary.py` from the dbt contract YAML and the raw Arrow",
        "schemas. Timestamps are UTC without a zone. Locally the layers are DuckDB schemas `raw`,",
        "`staging`, `intermediate` and `marts`; on Athena they are the Glue databases",
        "`musicpods_raw`, `musicpods_staging`, `musicpods_intermediate` and `musicpods_marts`.",
        "",
        "## Raw (Iceberg) tables",
        "",
        "Written by the Glue-style jobs (`src/musicpods/glue/jobs.py`) and the Firehose sink, each",
        "behind a data-quality gate (`src/musicpods/quality/checks.py`).",
        "",
    ]
    for name, (schema, desc) in RAW.items():
        lines += [f"### `raw.{name}`", "", desc, "", "| Column | Type |", "| --- | --- |"]
        lines += [f"| `{f.name}` | {f.type} |" for f in schema]
        lines.append("")
    for layer in ("marts",):
        lines += ["## Marts", "", "Contract-enforced dbt tables (`dbt/models/marts`).", ""]
        for path in sorted((MODELS / layer).rglob("_*.yml")):
            spec = yaml.safe_load(path.read_text(encoding="utf-8"))
            area = path.parent.name
            lines += [f"### {area.capitalize()}", ""]
            for model in spec.get("models", []):
                lines += [
                    f"#### `marts.{model['name']}`",
                    "",
                    _esc(model.get("description", "")),
                    "",
                    "| Column | Type | Description | Tests |",
                    "| --- | --- | --- | --- |",
                ]
                for col in model.get("columns", []):
                    lines.append(
                        f"| `{col['name']}` | {col.get('data_type', '')} | "
                        f"{_esc(col.get('description', ''))} | {_tests(col)} |"
                    )
                model_tests = [
                    next(iter(t)) if isinstance(t, dict) else t
                    for t in model.get("data_tests", []) or []
                ]
                if model_tests:
                    lines += ["", f"Model tests: {', '.join(model_tests)}."]
                lines.append("")
    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
